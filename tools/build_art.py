"""Art-override layer: copies the Graphic Designer's original illustrations into img/art/ and writes art-manifest.js.

Adding more art:  drop <exercise-name-in-kebab-case>.svg (or .webp/.png) into /workspace/business-ops/exercise-art/full/
                  (chip icons into .../chips/ or .../samples/chips/), then run:
                      python3 tools/build_art.py
                  and bump VERSION in sw.js before deploying.
Matching:  file slug == kebab-case library name (e.g. barbell-bench-press -> "Barbell Bench Press"), else the ALIAS table below,
           else an optional aliases.json in the art folder ({"slug": "Library Name"}), else "barbell-<slug>". Unmatched files are reported, not guessed.
Order: samples/ first, then full/ (full/ wins when a slug is in both).  Options: --badge  show the small muscle-map badge on art cards too."""
import json, os, re, shutil, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ART = '/workspace/business-ops/exercise-art'
args = [a for a in sys.argv[1:] if not a.startswith('--')]
if args: ART = args[0]
BADGE = '--badge' in sys.argv
EXTS = ('.svg', '.webp', '.png', '.jpg')
ALIAS = {'back-squat': 'Barbell Back Squat', 'bench-press': 'Barbell Bench Press', 'rdl': 'Romanian Deadlift', 'deadlift': 'Conventional Deadlift',
         'squat': 'Barbell Back Squat', 'overhead-press': 'Barbell Overhead Press', 'ohp': 'Barbell Overhead Press', 'pull-up': 'Pull-Up', 'hip-thrust': 'Barbell Hip Thrust'}
# designer chip file name -> Exercises-tab chip key (bodymap.js GROUPS, or a type chip)
CHIP_KEYS = {'chest': 'm-chest', 'back': 'm-back', 'biceps': 'm-biceps', 'triceps': 'm-triceps', 'quads': 'm-quads', 'quadriceps': 'm-quads',
             'hamstrings': 'm-hams', 'glutes': 'm-glutes', 'shoulders': 'm-shoulders', 'abs': 'm-core', 'core': 'm-core', 'calves': 'm-calves',
             'forearms': 'm-forearms', 'hips': 'm-hips', 'cardio': 'cardio'}
BACK_VIEW = {'m-back', 'm-triceps', 'm-hams', 'm-glutes', 'm-calves'}  # icons drawn from behind: get a small "back" marker in the chip
kebab = lambda s: re.sub(r'[^a-z0-9]+', '-', s.lower().replace("'", '').replace('’', '')).strip('-')

def main():
    s = open(os.path.join(ROOT, 'exercises-library.js')).read(); L = json.loads(s[s.index('{'):s.rindex('}') + 1])['items']
    idx = {kebab(it[0]): i for i, it in enumerate(L)}; byname = {it[0]: i for i, it in enumerate(L)}
    extra = {}
    for d in (ART, os.path.join(ART, 'full')):
        p = os.path.join(d, 'aliases.json')
        if os.path.exists(p): extra.update(json.load(open(p)))
    out, chips_out = os.path.join(ROOT, 'img', 'art'), os.path.join(ROOT, 'img', 'art', 'chips')
    if os.path.isdir(out): shutil.rmtree(out)
    os.makedirs(chips_out)
    files = {}
    for d in (os.path.join(ART, 'samples'), os.path.join(ART, 'full')):
        if os.path.isdir(d):
            for fn in sorted(os.listdir(d)):
                if fn.lower().endswith(EXTS): files[os.path.splitext(fn)[0].lower()] = os.path.join(d, fn)
    items, unmatched = {}, []
    for slug, path in sorted(files.items()):
        name = extra.get(slug) or ALIAS.get(slug)
        i = byname.get(name) if name else idx.get(slug, idx.get('barbell-' + slug))
        if i is None: unmatched.append(slug); continue
        fn = kebab(L[i][0]) + os.path.splitext(path)[1].lower()
        shutil.copyfile(path, os.path.join(out, fn)); items[str(i)] = fn
    chips = {}
    for d in (os.path.join(ART, 'samples', 'chips'), os.path.join(ART, 'chips'), os.path.join(ART, 'full', 'chips')):
        if os.path.isdir(d):
            for fn in sorted(os.listdir(d)):
                base, ext = os.path.splitext(fn.lower())
                if ext in EXTS and base in CHIP_KEYS:
                    shutil.copyfile(os.path.join(d, fn), os.path.join(chips_out, base + ext)); chips[CHIP_KEYS[base]] = 'chips/' + base + ext
    js = ('/* SlimTucci art overrides: original illustrations by the SlimTucci Graphic Designer (img/art/). Generated by tools/build_art.py, do not hand-edit.\n'
          '   items: library index -> file; chips: Exercises-tab chip key -> icon; back: chip icons drawn from behind. */\n'
          'window.SLIMTUCCI_ART = ' + json.dumps({'version': 1, 'badge': BADGE, 'items': items, 'chips': chips, 'back': sorted(k for k in chips if k in BACK_VIEW)},
                                                 separators=(',', ':')) + ';\n')
    open(os.path.join(ROOT, 'art-manifest.js'), 'w').write(js)
    print(f'{len(items)} illustrations -> ' + ', '.join(f'{L[int(i)][0]}' for i in items) + f'; {len(chips)} chip icons ({", ".join(sorted(chips))})')
    if unmatched: print('NOT matched (rename the file to the kebab-case library name, or add it to aliases.json):', ', '.join(unmatched))

if __name__ == '__main__':
    main()
